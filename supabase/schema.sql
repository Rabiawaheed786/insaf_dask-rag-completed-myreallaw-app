-- Insaf Dastak: Supabase user table.
-- FastAPI app isi table ko padhta/likhta hai; password kabhi plain save nahi hota.
-- Supabase SQL Editor mein chala kar table bana lein.
-- Id bigint hai kyunke app ke baqi tables (sessions, requests) integer user id use karte hain.

create table if not exists public.users (
  id bigint generated by default as identity primary key,
  email text not null unique,
  password_hash text not null,
  display_name text not null default '',
  role text not null default 'user'
    check (role in ('user', 'lawyer', 'coordinator', 'admin')),
  language text not null default 'roman_urdu'
    check (language in ('roman_urdu', 'en')),
  timezone text not null default 'Asia/Karachi',
  failed_logins integer not null default 0,
  locked_until timestamptz,
  created_at timestamptz not null default now()
);

create index if not exists users_email_lower_idx on public.users (lower(email));

-- Table par RLS on hai aur anon/authenticated ke liye koi policy nahi:
-- sirf backend (service role / database connection) hi access kar sakta hai.
alter table public.users enable row level security;
revoke all on public.users from anon, authenticated;
grant all on public.users to service_role;
